/**
 * One AI style variation of a protected template (variations/service.ts): its single image request and the local work
 * around it.
 *
 *   prepare_variation  free    the approved text-free base and the wordless guide, both checked against the variation
 *   generate_artwork   PAID    one image request (ai/calls.ts imageCall: estimate, budget hold, call, usage), never retried
 *   check_artwork      free    the local recognizer reads the new artwork; any text it finds is reported, never hidden
 *   layout_variation   free    the template's words and logos placed in variant coordinates, then every layout check
 *
 * A refusal or a failed request fails the variation; nothing is substituted for the artwork. A server stop during the paid
 * stage marks it outcome_unknown (the runner's rule): it is not sent again.
 */
import sharp from "sharp";
import { blockingIssues, type ProtectedTemplate } from "@frameflow/shared";
import { imageCall } from "../../ai/calls.js";
import { ingestAsset } from "../../assets/ingest.js";
import { readStorageFile } from "../../storage.js";
import { now } from "../../store.js";
import { layoutOnArtwork, variationTemplate } from "../../variations/service.js";
import { plausibleWord } from "../../../textRecognition/recognizer.js";
import { JobStageError, type JobKindDef, type StageContext } from "../runner.js";

export interface GenerateStyleVariationInput { variationId: string }

function context(ctx: StageContext) {
  const input = ctx.job.inputSnapshot as GenerateStyleVariationInput;
  const record = ctx.db.styleVariations.require(input.variationId, "Style variation");
  const store = ctx.deps.protectedStore?.();
  if (!store) throw new JobStageError("not_configured", "Protected templates are not available to this worker.");
  let src;
  try { src = variationTemplate(store, record.templateId); }
  catch (err) { throw new JobStageError("template_not_ready", err instanceof Error ? err.message : String(err)); }
  return { record, src, template: src.template as ProtectedTemplate };
}
const event = (ctx: StageContext, variationId: string, action: "generated" | "checked" | "failed", detail: string) =>
  ctx.db.styleVariations.update(variationId, (x) => ({ updatedAt: now(), review: { ...x.review, history: [...x.review.history, { at: now(), action, detail }] } }));

export const generateStyleVariationJob: JobKindDef = {
  kind: "generate_style_variation",
  stages: [
    {
      name: "prepare_variation",
      state: "composing",
      paid: false,
      async run(ctx) {
        const { record, template } = context(ctx);
        if (record.source !== "ai" || !record.generation) throw new JobStageError("invalid", "Only AI variations are generated by a job.");
        if (template.base!.sha256 !== record.parent.baseSha256) throw new JobStageError("base_changed", "The template's base changed after this variation was requested. Request it again.");
        const guide = ctx.db.assets.require(record.guideAssetId, "Layout guide");
        // The guide must still be wordless boxes on grey: it is the only other picture the model sees.
        if (guide.role !== "layout_guide") throw new JobStageError("invalid", "The layout guide is not a guide.");
        return { baseSha256: template.base!.sha256, guideAssetId: guide.id, providerSize: record.generation.providerSize };
      },
    },
    {
      name: "generate_artwork",
      state: "generating",
      paid: true,
      async run(ctx) {
        const { record, src } = context(ctx);
        const env = ctx.deps.env, provider = ctx.deps.provider;
        if (!env || !provider) throw new JobStageError("not_configured", "The image provider is not configured on this server.");
        const g = record.generation!, [w, h] = g.providerSize.split("x").map(Number);
        const guide = ctx.db.assets.require(record.guideAssetId, "Layout guide");
        const base = await sharp(src.base).rotate().resize(w, h, { fit: "fill" }).removeAlpha().png().toBuffer();
        const guidePng = await sharp(await readStorageFile(ctx.deps.storageDir, guide.normalisedPath)).resize(w, h, { fit: "fill" }).png().toBuffer();
        // The provider's own safety system applies unchanged; a refusal fails this stage (and the variation).
        const res = await imageCall({ db: ctx.db, env, provider, job: ctx.job }, `variation:${record.id}`, {
          model: g.model, prompt: g.prompt, size: g.providerSize, quality: g.quality,
          images: [{ data: base, mime: "image/png", name: "text-free-base.png" }, { data: guidePng, mime: "image/png", name: "layout-guide.png" }],
        });
        const raw = await ingestAsset({ buffer: res.image, role: "generated_scene", filename: `variation-${record.id}-raw.png`, label: `${record.preset.name} · ${g.model} output` }, { db: ctx.db, storageDir: ctx.deps.storageDir });
        // Fitted to the template canvas (same aspect, within the provider's 16-pixel steps), so every slot lines up.
        const fitted = await sharp(res.image).resize(record.layout.canvas.width, record.layout.canvas.height, { fit: "fill", kernel: "lanczos3" }).removeAlpha().png().toBuffer();
        const art = await ingestAsset({ buffer: fitted, role: "generated_scene", filename: `variation-${record.id}.png`, label: `${record.preset.name} · AI artwork` }, { db: ctx.db, storageDir: ctx.deps.storageDir });
        ctx.db.styleVariations.update(record.id, (x) => ({ artworkAssetId: art.asset.id, rawArtworkAssetId: raw.asset.id, generation: { ...x.generation!, requestId: res.requestId }, updatedAt: now() }));
        event(ctx, record.id, "generated", `${g.model} ${g.quality} ${g.providerSize}, request ${res.requestId ?? "(no id)"}${res.costMicroUsd === null ? ", cost unknown (no usage reported)" : ""}.`);
        return { artworkAssetId: art.asset.id, rawArtworkAssetId: raw.asset.id, requestId: res.requestId, estimateMicroUsd: res.estimateMicroUsd, costMicroUsd: res.costMicroUsd };
      },
    },
    {
      name: "check_artwork",
      state: "reviewing",
      paid: false,
      async run(ctx) {
        const { record } = context(ctx);
        const recognizer = ctx.deps.recognizer?.();
        const asset = ctx.db.assets.require(record.artworkAssetId, "Artwork");
        if (!recognizer) {
          const check = { status: "not_run" as const, words: [], note: "No local recognizer on this server: the artwork was not checked for drawn text. Look at it closely." };
          ctx.db.styleVariations.update(record.id, { artworkCheck: check, updatedAt: now() });
          return check;
        }
        const image = await sharp(await readStorageFile(ctx.deps.storageDir, asset.normalisedPath)).resize({ width: 1600, height: 1600, fit: "inside", withoutEnlargement: true }).png().toBuffer();
        const read = await recognizer.recognize({ image, region: { x: 0, y: 0, width: asset.width, height: asset.height }, purpose: "artwork-check" });
        // Readings of two or more letters or digits with fair confidence: decorative shapes misread as one letter are left out.
        const words = read.filter((w) => plausibleWord(w, 0.6) && (w.text.match(/[\p{L}\p{N}]/gu)?.length ?? 0) >= 2).map((w) => ({ text: w.text, confidence: Math.round(w.confidence * 100) / 100 }));
        const check = { status: words.length ? ("text_found" as const) : ("clean" as const), words,
          note: words.length ? "The local recognizer read text in the generated artwork. The image model was told never to draw text; check the artwork before using it." : `No text read by ${recognizer.engine.name}. A local check can miss stylised lettering: look at the artwork too.` };
        ctx.db.styleVariations.update(record.id, { artworkCheck: check, updatedAt: now() });
        event(ctx, record.id, "checked", check.status === "clean" ? "No drawn text found." : `Drawn text found: ${words.map((w) => `“${w.text}”`).join(", ")}.`);
        return check;
      },
    },
    {
      name: "layout_variation",
      state: "composing",
      paid: false,
      async run(ctx) {
        const { record, src } = context(ctx);
        const placed = await layoutOnArtwork(ctx.db, ctx.deps.storageDir, ctx.db.styleVariations.require(record.id, "Style variation"), src.analysis);
        const status = blockingIssues(placed.validation).length ? ("needs_review" as const) : ("ready" as const);
        ctx.db.styleVariations.update(record.id, { ...placed, status, parent: { ...record.parent, analysisRevision: src.analysis.revision }, updatedAt: now() });
        return { status, issues: placed.validation.issues.length };
      },
    },
  ],
  finish(outputs) {
    const layout = outputs.layout_variation as { status: "ready" | "needs_review" } | undefined;
    return { state: layout?.status === "ready" ? "complete" : "needs_review", result: outputs.layout_variation };
  },
};
