import { test, expect } from '@playwright/test';
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import type { ProjectDocument } from '@frameflow/shared';
import type { ProductView } from '../../client/src/features/productTemplates/api';
const API = '/api/layerize-experiment/product-templates', OUT = process.env.PRODUCT_WORDS_OUT ?? 'test-results/product-v2/screens';
test.use({ extraHTTPHeaders: { origin: `http://127.0.0.1:${process.env.FRAMEFLOW_OFFLINE_E2E_PORT ?? 3317}` } });
test.setTimeout(300000);
test('Ganesh: word overlays, selective layers, dashboard, editor edit/save/reopen/export (handmade manifest)', async ({ page, request }) => {
  mkdirSync(OUT, { recursive: true });
  await page.route(url => /^https?:$/.test(url.protocol) && url.hostname !== '127.0.0.1', r => r.abort());
  await page.goto('/');
  await page.getByRole('button', { name: 'OpenAI + Seedream test' }).click();
  const panel = page.getByRole('dialog', { name: 'OpenAI + Seedream test' });
  await panel.getByRole('tab', { name: 'Offer Templates', exact: true }).click();
  await panel.getByRole('button', { name: 'New product template' }).click();
  const sheet = await (await request.get('/__test__/ganesh-sheet.png')).body();
  await panel.getByLabel('Creative to upload').setInputFiles({ name: 'Ganesh.png', mimeType: 'image/png', buffer: sheet });
  await expect(panel.getByText('This picture has 4 creatives')).toBeVisible();
  await panel.getByLabel('Template name').fill('Ganesh word verification');
  await panel.getByRole('checkbox', { name: /Find characters and products with AI/ }).check();
  const created = page.waitForResponse(r => r.url().endsWith(API) && r.request().method() === 'POST');
  await panel.getByRole('button', { name: 'Upload and find elements' }).click();
  const id = ((await (await created).json()) as ProductView).template.id;
  await expect(panel.getByRole('heading', { name: 'Here’s what we found' })).toBeVisible({ timeout: 120000 });
  let view = await (await request.get(`${API}/${id}`)).json() as ProductView;
  expect(view.counts).toMatchObject({ characters: 1, products: 8, logos: 18, words: 42 });
  await panel.getByRole('region', { name: 'Characters', exact: true }).getByRole('button', { name: /Ganesha/ }).click();
  await page.screenshot({ path: `${OUT}/01-detection.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: `${OUT}/02-mobile-review.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await panel.getByRole('button', { name: 'Save and choose what to decompose' }).click();
  await expect(panel.getByRole('heading', { name: 'Choose what to decompose' })).toBeVisible();
  await panel.getByRole('button', { name: 'Continue to Decomposition' }).click();
  await expect(panel.getByRole('heading', { name: 'Inspect the layers and the background' })).toBeVisible({ timeout: 120000 });
  view = await (await request.get(`${API}/${id}`)).json();
  const file = (f: string) => `/api/layerize-experiment/protected-templates/${id}/files/${f}`;
  for (const [name, f] of [['original', view.template.source.inputFile], ['clean', view.product.prepared!.clean.file], ['background', view.product.prepared!.base.file], ['reconstructed', view.product.prepared!.previews.recombined]]) writeFileSync(`${OUT}/${name}.png`, await (await request.get(file(f))).body());
  for (const o of view.product.objects.filter(o => o.cutout)) writeFileSync(`${OUT}/cutout-${o.kind}-${o.id}.png`, await (await request.get(file(o.cutout!.file))).body());
  expect(view.product.objects.filter(o => o.cutout)).toHaveLength(9);
  expect(view.product.prepared!.quality.clean.visiblePercent).toBeLessThan(0.01);
  await panel.getByRole('tab', { name: 'Without text and logos' }).click();
  await page.screenshot({ path: `${OUT}/03-clean.png` });
  await panel.getByRole('tab', { name: 'Background only' }).click();
  await page.screenshot({ path: `${OUT}/03b-background.png` });
  for (const c of await panel.getByRole('complementary', { name: 'Checks' }).getByRole('checkbox').all()) { await expect(c).toBeEnabled(); await c.check(); }
  await panel.getByRole('button', { name: 'Save master template' }).click();
  await panel.getByRole('button', { name: 'Use this template' }).click();
  await panel.getByRole('button', { name: 'New creative' }).click();
  const sent = page.waitForResponse(r => r.url().endsWith('/open') && r.request().method() === 'POST');
  await panel.getByRole('button', { name: 'Send to Decomposition', exact: true }).click();
  const { runId } = await (await sent).json();
  await expect(panel.getByTestId('creative-run-note')).toBeVisible();
  await page.screenshot({ path: `${OUT}/04-run.png` });
  const run = await (await request.get(`/api/layerize-experiment/runs/${runId}`)).json();
  expect(run.creative.texts).toHaveLength(42);
  // Each character and product its own layer (9); each display stand found when preparing its own layer too.
  const objectLayers = run.creative.layers.filter((l: { kind: string }) => l.kind === 'object') as { file: string; elementIds: string[] }[], standIds = (view.product.prepared!.stands ?? []).map(s => s.id);
  expect(standIds.length).toBeGreaterThan(0);
  expect(objectLayers.filter(l => /-(product|character)\.png$/.test(l.file))).toHaveLength(9);
  expect(objectLayers.filter(l => /-stand\.png$/.test(l.file)).map(l => l.elementIds[0]).sort()).toEqual([...standIds].sort());
  expect(objectLayers).toHaveLength(9 + standIds.length);
  await panel.getByRole('button', { name: 'Open in editor', exact: true }).click();
  await expect(panel).toBeHidden();
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('frameflow:project:v1')!) as ProjectDocument);
  await expect.poll(async () => (await stored()).variants.some(v => v.productTemplate)).toBe(true);
  const before = (await stored()).variants.find(v => v.productTemplate)!;
  expect(before.elements).toHaveLength(42);
  expect(before.elements.every(w => w.type === 'text' && w.protectedSlot?.word)).toBe(true);
  await page.getByRole('tab', { name: 'Text', exact: true }).click();
  await page.locator('.text-elements summary').filter({ hasText: 'A grand welcome' }).click();
  await page.getByRole('button', { name: 'Select word grand', exact: true }).first().click();
  const grand = before.elements.filter(w => w.text === 'grand').sort((a,b) => a.protectedSlot!.word!.order - b.protectedSlot!.word!.order)[0];
  await page.getByLabel('X', { exact: true }).fill(String(grand.x + 30));
  await page.getByLabel('X', { exact: true }).press('Enter');
  await page.getByLabel('Text content', { exact: true }).fill('amazing');
  await page.getByLabel('Text content', { exact: true }).blur();
  await expect.poll(async () => (await stored()).variants.find(v => v.id === before.id)!.elements.find(w => w.id === grand.id)!.text).toBe('amazing');
  const after = (await stored()).variants.find(v => v.id === before.id)!;
  expect(after.elements.find(w => w.id === grand.id)!.x).toBeCloseTo(grand.x + 30, 1);
  expect(after.elements.filter(w => w.id !== grand.id)).toEqual(before.elements.filter(w => w.id !== grand.id));
  await page.screenshot({ path: `${OUT}/05-editor-edited.png` });
  const logo = before.layers!.find(l => l.name === 'LG logo')!;
  await page.locator('.layer-select', { hasText: 'LG logo' }).first().click();
  await page.getByLabel('X', { exact: true }).fill(String(logo.x - 12));
  await page.getByLabel('X', { exact: true }).blur();
  await expect.poll(async () => (await stored()).variants.find(v => v.id === before.id)!.layers!.find(l => l.id === logo.id)!.x).toBe(logo.x - 12);
  await page.screenshot({ path: `${OUT}/05b-logo-moved.png` });
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export PNG', exact: true }).click();
  const exported = await download; await exported.saveAs(`${OUT}/export.png`);
  const meta = await sharp(`${OUT}/export.png`).metadata();
  expect([meta.width, meta.height]).toEqual([view.template.source.width, view.template.source.height]);
  await page.reload();
  await page.getByRole('button', { name: 'OpenAI + Seedream test' }).click();
  await panel.getByRole('tab', { name: 'Saved Runs', exact: true }).click();
  await panel.getByRole('article', { name: `Saved run ${runId}`, exact: true }).getByRole('button', { name: /View run/ }).click();
  await panel.getByRole('button', { name: 'Open in editor', exact: true }).click();
  await expect(panel).toBeHidden();
  expect((await stored()).variants.find(v => v.id === before.id)!.elements).toEqual(after.elements);
  expect((await stored()).variants.find(v => v.id === before.id)!.layers!.find(l => l.id === logo.id)!.x).toBe(logo.x - 12);
  await page.getByRole('tab', { name: 'Text', exact: true }).click();
  await page.locator('.text-elements summary').filter({ hasText: 'A amazing welcome' }).click();
  await page.getByRole('button', { name: 'Select word amazing', exact: true }).click();
  await expect(page.getByLabel('Text content', { exact: true })).toHaveValue('amazing');
  await page.screenshot({ path: `${OUT}/06-reopened.png` });
  writeFileSync(`${OUT}/../browser-evidence.json`, JSON.stringify({ runId, counts: view.counts, before: grand, after: after.elements.find(w => w.id === grand.id), neighborsUnchanged: true, logoMovedAndReopened: true, export: [meta.width, meta.height], fixture: 'handmade, not AI quality' }, null, 2));
});
